  const lower = s => String(s || '').toLocaleLowerCase('sr-Latn-RS');
  // Interpret exact binomial, including 'x' hybrids; avoid translating cultivar epithets.
  function baseKey(latinName) {
    const parts = String(latinName || '').trim().split(/\s+/);
    if (parts.length < 2) return '';
    const epithet = parts[1];
    if (/^(?:x|×)$/i.test(epithet) && parts.length > 2) return [parts[0], 'x', parts[2]].join(' ');
    if (!/^[a-z][a-z.-]*$/i.test(epithet) || /^['"(]/.test(epithet)) return '';
    return parts[0] + ' ' + epithet;
  }
  function resolve(plant) {
    const verified = String(plant?.commonName || '').trim();
    if (verified) return {name: verified, level: 'existing', note: 'Domaći naziv iz postojeće baze'};
    const exact = speciesLabels[baseKey(plant?.latinName)];
    if (exact) return {name: exact, level: 'species', note: 'Naziv botaničke vrste; kultivar ostaje označen latinski'};
    const genus = String(plant?.latinName || '').split(/\s+/)[0];
    const broad = genusLabels[genus];
    if (broad) return {name: broad, level: 'genus', note: 'Domaći naziv roda ili hortikulturne grupe; precizan narodni naziv vrste nije potvrđen'};
    return {name: '', level:'unknown', note:'Domaći naziv nije potvrđen'};
  }
  root.DemetraVernacular = Object.freeze({
    resolve, genusLabels:Object.freeze(genusLabels), speciesLabels:Object.freeze(speciesLabels)
  });
